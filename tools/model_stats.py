#!/usr/bin/env python
"""Emit the layer-by-layer parameter and FLOP tables for reports/MODEL_REPORT.md.

    python tools/model_stats.py > reports/_model_stats.md
"""

from __future__ import annotations

import torch

from hangman.config import ExperimentConfig, GLOBAL_FEATURE_DIM, VOCAB_SIZE
from hangman.models import build_model
from hangman.models.layers import count_parameters

SPECS = {
    "HangmanFormer-M (primary)": dict(arch="transformer", d_model=512, n_layers=8, n_heads=8, d_ff=1408),
    "HangmanBiGRU": dict(arch="bigru", d_model=640, rnn_layers=4),
    "HangmanDilatedCNN": dict(arch="dilated_cnn", d_model=448, cnn_layers=8),
}


def build(spec: dict):
    cfg = ExperimentConfig().model
    for key, value in spec.items():
        setattr(cfg, key, value)
    return build_model(cfg), cfg


def transformer_breakdown(cfg) -> list[tuple[str, str, int]]:
    """Per-sublayer parameter counts for one encoder block."""
    d, ff = cfg.d_model, cfg.d_ff
    return [
        ("RMSNorm (attn)", f"({d},)", d),
        ("QKV projection", f"({d}, {3 * d})", 3 * d * d),
        ("output projection", f"({d}, {d})", d * d),
        ("RMSNorm (ffn)", f"({d},)", d),
        ("SwiGLU gate", f"({d}, {ff})", d * ff),
        ("SwiGLU up", f"({d}, {ff})", d * ff),
        ("SwiGLU down", f"({ff}, {d})", ff * d),
    ]


def main() -> None:
    print("<!-- generated by tools/model_stats.py; do not edit by hand -->\n")

    for name, spec in SPECS.items():
        model, cfg = build(spec)
        total = count_parameters(model)
        print(f"### {name}\n")
        print(f"| Module | Parameters | % of total | Kind |")
        print(f"|---|---:|---:|---|")
        for module, count, kind in model.parameter_report():
            if module == "TOTAL":
                continue
            print(f"| `{module}` | {count:,} | {100 * count / total:.1f}% | {kind} |")
        print(f"| **TOTAL** | **{total:,}** | 100% | |")
        print()

    # Per-block detail for the primary model.
    model, cfg = build(SPECS["HangmanFormer-M (primary)"])
    print("### HangmanFormer-M — inside one encoder block (×8)\n")
    print("| Sub-layer | Shape | Parameters |")
    print("|---|---|---:|")
    block_total = 0
    for label, shape, count in transformer_breakdown(cfg):
        print(f"| {label} | {shape} | {count:,} |")
        block_total += count
    print(f"| **per block** | | **{block_total:,}** |")
    print(f"| **× {cfg.n_layers} blocks** | | **{block_total * cfg.n_layers:,}** |")
    print()

    print("### HangmanFormer-M — everything outside the blocks\n")
    print("| Component | Shape | Parameters |")
    print("|---|---|---:|")
    d = cfg.d_model
    rows = [
        ("token embedding", f"({VOCAB_SIZE}, {d})", VOCAB_SIZE * d),
        ("absolute position embedding", f"(1, 32, {d})", 32 * d),
        ("global MLP", f"({GLOBAL_FEATURE_DIM}→{d}→{d})", GLOBAL_FEATURE_DIM * d + d + d * d + d),
        ("FiLM trunk", f"({GLOBAL_FEATURE_DIM}→128→128)", GLOBAL_FEATURE_DIM * 128 + 128 + 128 * 128 + 128),
        ("FiLM heads", f"8 × (128 → {4 * d})", 8 * (128 * 4 * d + 4 * d)),
        ("final RMSNorm", f"({d},)", d),
        ("set_head", f"({d}→{d}→26)", d * d + d + d * 26 + 26),
        ("pos_head", f"({d}, 26)", d * 26 + 26),
        ("count_head", f"({d}, 104)", d * 104 + 104),
        ("value_head", f"({d}→{d // 4}→1)", d * (d // 4) + d // 4 + d // 4 + 1),
    ]
    for label, shape, count in rows:
        print(f"| {label} | {shape} | {count:,} |")
    print()

    # Inference cost.
    total = count_parameters(model)
    mean_guesses = 10.6
    n_test = 250_000
    states = n_test * mean_guesses
    mean_seq = 10.4      # CLS + mean word length, with length-bucketed batches
    flops = 2 * total * mean_seq * states
    print("### Inference cost for the full test set\n")
    print("| Quantity | Value |")
    print("|---|---:|")
    print(f"| Test words | {n_test:,} |")
    print(f"| Mean guesses per game (measured) | {mean_guesses} |")
    print(f"| State evaluations | {states / 1e6:.1f} M |")
    print(f"| Mean padded sequence length | {mean_seq} |")
    print(f"| Forward FLOPs (2·N·L per state) | {flops / 1e15:.2f} PFLOP |")
    print(f"| At 56 TFLOPS (measured, this shape) | {flops / 56e12:.0f} s |")
    print(f"| At 10 TFLOPS (a Kaggle T4, conservatively) | {flops / 10e12 / 60:.0f} min |")


if __name__ == "__main__":
    main()
